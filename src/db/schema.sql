CREATE TABLE IF NOT EXISTS proposals (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  customer_id BIGINT NOT NULL,
  title VARCHAR(160) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'sent', 'accepted', 'rejected')),
  valid_until DATE NULL,
  notes VARCHAR(2000) NULL,
  total DECIMAL(10,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT proposals_customer_fk FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT

);

CREATE TABLE IF NOT EXISTS proposal_items (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  proposal_id BIGINT NOT NULL,
  service_id BIGINT NULL,
  service_name VARCHAR(120) NOT NULL,
  description VARCHAR(2000) NULL,
  quantity SMALLINT NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL,
  line_total DECIMAL(10,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT proposal_items_proposal_fk FOREIGN KEY (proposal_id) REFERENCES proposals(id) ON DELETE CASCADE,
  CONSTRAINT proposal_items_service_fk FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE SET NULL

);

CREATE INDEX IF NOT EXISTS proposals_customer_index ON proposals (customer_id);

CREATE INDEX IF NOT EXISTS proposals_status_index ON proposals (status);

CREATE OR REPLACE TRIGGER proposals_set_updated_at BEFORE UPDATE ON proposals FOR EACH ROW EXECUTE FUNCTION fnsc_set_updated_at();

CREATE INDEX IF NOT EXISTS proposal_items_proposal_index ON proposal_items (proposal_id);

CREATE TABLE IF NOT EXISTS proposal_status_history (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  proposal_id BIGINT NOT NULL,
  previous_status VARCHAR(24) NULL CHECK (previous_status IN ('draft', 'sent', 'accepted', 'rejected')),
  new_status VARCHAR(24) NOT NULL CHECK (new_status IN ('draft', 'sent', 'accepted', 'rejected')),
  user_id BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT proposal_status_history_proposal_fk FOREIGN KEY (proposal_id) REFERENCES proposals(id) ON DELETE CASCADE,
  CONSTRAINT proposal_status_history_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL

);

INSERT INTO proposal_status_history (proposal_id, previous_status, new_status, user_id, created_at)
SELECT p.id, NULL, p.status, NULL, p.created_at
FROM proposals p
LEFT JOIN proposal_status_history h ON h.proposal_id = p.id
WHERE h.id IS NULL;

CREATE INDEX IF NOT EXISTS proposal_status_history_proposal_index ON proposal_status_history (proposal_id, created_at);

CREATE TABLE IF NOT EXISTS contracts (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  proposal_id BIGINT NOT NULL,
  customer_id BIGINT NOT NULL,
  customer_name VARCHAR(120) NOT NULL,
  customer_company VARCHAR(120) NULL,
  customer_email VARCHAR(254) NULL,
  title VARCHAR(160) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'signed', 'cancelled')),
  effective_date DATE NULL,
  end_date DATE NULL,
  payment_terms VARCHAR(1000) NULL,
  clauses TEXT NULL,
  total DECIMAL(10,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT contracts_proposal_unique UNIQUE (proposal_id),
  CONSTRAINT contracts_proposal_fk FOREIGN KEY (proposal_id) REFERENCES proposals(id) ON DELETE RESTRICT,
  CONSTRAINT contracts_customer_fk FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT

);


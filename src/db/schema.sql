CREATE TABLE IF NOT EXISTS contract_revisions (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  contract_id BIGINT NOT NULL,
  revision_number INTEGER NOT NULL,
  title VARCHAR(160) NOT NULL,
  effective_date DATE NULL,
  end_date DATE NULL,
  payment_terms VARCHAR(1000) NULL,
  clauses TEXT NULL,
  total DECIMAL(10,2) NOT NULL,
  created_by BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT contract_revisions_number_unique UNIQUE (contract_id, revision_number),
  CONSTRAINT contract_revisions_contract_fk FOREIGN KEY (contract_id) REFERENCES contracts(id) ON DELETE CASCADE,
  CONSTRAINT contract_revisions_user_fk FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL

);

INSERT INTO contract_revisions
  (contract_id, revision_number, title, effective_date, end_date, payment_terms, clauses, total, created_by)
SELECT c.id, 1, c.title, c.effective_date, c.end_date, c.payment_terms, c.clauses, c.total, NULL
FROM contracts c
LEFT JOIN contract_revisions r ON r.contract_id = c.id
WHERE r.id IS NULL;

CREATE INDEX IF NOT EXISTS contract_revisions_created_by_index ON contract_revisions (created_by);

CREATE TABLE IF NOT EXISTS contract_status_history (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  contract_id BIGINT NOT NULL,
  status VARCHAR(24) NOT NULL CHECK (status IN ('draft', 'signed', 'cancelled')),
  changed_by BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT contract_status_history_contract_fk FOREIGN KEY (contract_id) REFERENCES contracts(id) ON DELETE CASCADE,
  CONSTRAINT contract_status_history_user_fk FOREIGN KEY (changed_by) REFERENCES users(id) ON DELETE SET NULL

);

INSERT INTO contract_status_history (contract_id, status, changed_by)
SELECT c.id, c.status, NULL
FROM contracts c
LEFT JOIN contract_status_history h ON h.contract_id = c.id
WHERE h.id IS NULL;

CREATE INDEX IF NOT EXISTS contract_status_history_contract_index ON contract_status_history (contract_id, id);

CREATE INDEX IF NOT EXISTS contract_status_history_user_index ON contract_status_history (changed_by);

